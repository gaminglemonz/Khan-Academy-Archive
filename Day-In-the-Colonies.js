const Camera = (function(){
    /**
    
    Translates the entire game canvas to focus on one object
    
    @constructor
    
    @params {object} target - The object the camera should focus on
    
    **/
    const _Camera = function(target){
        // Set camera's position
        this.x = target.x || 0;
        this.y = target.y || 0;
        
        // Set target
        this.target = target;
        
        // No smooth movement (mainly for development)
        this.stiff = false;
        
        // Shake timer
        this.shakeTimer = 10;
    };
    _Camera.prototype.follow = function(){
        if (this.stiff){
            this.x = this.target.x + this.target.w/2 - width/2;
            this.y = this.target.y - height/2;
        } else {
            this.x = lerp(this.x, this.target.x + this.target.w/2 - width/2 + (!game.inElevator?(mouseX-width/2)/3:0), 0.05);
            this.y = lerp(this.y, this.target.y - height/2+ (!game.inElevator?(mouseY-height/2)/3:0), 0.05);
        }
        this.x = constrain(this.x, game.levels[game.lvl].map.length>1?0:-Infinity, game.levels[game.lvl].map[0].length * BLOCKSIZE - width);
    };
    _Camera.prototype.shake = function(intensity){ 
        this.x += Math.random() * intensity;
        this.y += Math.random() * intensity;
    };
    return _Camera;
})();

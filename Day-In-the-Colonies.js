function keyReleased(){
    if (keys.r && !game.inElevator){
        Day.reset();
        game.loadLevel();
        game.inactive = false;
        game.onDeath = false;
    }
    if (keys[LEFT] && game.scene === 'story' && game.curLine > 0){
        game.curLine --;
        game.timer = 0;
    }
    if (keys[RIGHT] && game.scene === 'story' && game.curLine < game.storylines.length - 1){
        game.curLine ++;
        game.timer = 0;
    }
    delete keys[keyCode];
    delete keys[String(key).toLowerCase()];
}

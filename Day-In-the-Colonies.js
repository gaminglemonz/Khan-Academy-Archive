// CREATE STAR CIRCLE \\
function starCircle(x, y, num, radius, sz, clr){
    angleMode = 'radians';
    pushMatrix();
    imageMode(CENTER);
    translate(x, y);
    for (let i = 0; i < num; i ++){
        const angle = 2 * Math.PI * i / num;
        const X = radius * cos(angle);
        const Y = radius * sin(angle);
        image(imgs[clr+'_star'], X, Y, sz, sz);
    }
    popMatrix();
    angleMode = 'degrees';
}


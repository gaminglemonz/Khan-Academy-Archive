const Button = (function(){
    /**
    
    Create a button that changes the scene of the game
    
    @constructor
    
    @params {object} config - Configure the button's properties
    @property {number} config.x - X-coordinate in pixels
    @property {number} config.y - Y-coordinate in pixels
    @property {number} config.w - Width in pixels
    @property {number} config.h - Height in pixels
    @property {string} config.txt - Set the text that's displayed on the  button
    @property {string} config.to - Which scene the game will go to when the button is clicked
    
    **/
    const _Button = function(config){
        // Position of button
        this.x = config.x || 0;
        this.y = config.y || 0;
        
        // Size of the button
        this.w = config.w || 100;
        this.h = config.h || 50;
        
        // Text displayed
        this.txt = config.txt || "placeholder";
        this.txtSz = config.txtSz || 4;
        
        // Scene to switch to
        this.to = config.to || 'menu';
        
        // Hover & click effects
        this.bg = this.over() ? 255 : 0;
        this.bgColor = 0;
        this.wasClicked = false;
    };
    
    // Display the button
    _Button.prototype.display = function(){
        stroke(this.over() ? 0 : 255);
        strokeWeight(2);
        fill(color(this.bgColor));
        rect(this.x, this.y , this.w, this.h);
        
        noStroke();
        Text(this.txt.substring(0, game.timer-80), this.x+this.w/5-this.txt.length*4, this.y+this.h/5, this.txtSz, this.over() ? 0 : 255);
        
        if (this.over()){
            this.bgColor = lerp(this.bgColor, 255, 0.1);
            cursor(HAND);
        } else {
            this.bgColor = lerp(this.bgColor, 0, 0.1);
        }
        
        if (this.clicked()){
            game.transition.run();
            game.transition.reset();
            this.wasClicked = true;
        }
        if (!game.transition.fadeIn && this.wasClicked){
            this.wasClicked = false;
            game.scene = this.to;
        }
    };
    _Button.prototype.over = function(){
        return mouseX > this.x && mouseX < this.x + this.w &&
               mouseY > this.y && mouseY < this.y + this.h;
    };
    _Button.prototype.clicked = function(){
        return this.over() && clicked && !this.wasClicked;
    };
    return _Button; // Return _Button class
})();

var Text = function(txt, x, y, size, rgb) {
    var spaceX = 0;
    var spaceY = 0;
    txt = txt.toUpperCase();
    for(var i = 0; i < txt.length; i++) {
        if(txt[i] !== " "&&txt[i]!==" " && txt[i] !== "\n") {
            letters(txt[i], spaceX + x, spaceY + y, size, rgb);
        }
        if(txt[i] === "M" || txt[i] === "W") {
            spaceX += size * 2;
        }
        spaceX += size * 4;
        if(txt[i] === " " || txt[i] === "." || txt[i] === "'") {
            spaceX -= size * 2;
        }
        if(txt[i] === " "){
            spaceX -= size;
        }
        if(txt[i] === "\n") {
            spaceY += size * 8;
            spaceX = 0;
        }
    }
};


const Robot = (function(){
    /** 
    
    Create a robot that will attack the player
    
    @constructor
    
    @params {object} config - Configure the robot
    @property {number} config.x - Set robot's x position
    @property {number} config.y - Set robot's y position
    
    **/
    const _Robot = function(config){
        // Robot's position
        this.x = config.x || 0;
        this.y = config.y || 0;
        
        // Robot's size
        this.szOffset = Math.random();
        this.w = BLOCKSIZE * (1 + this.szOffset);
        this.h = BLOCKSIZE * (1 + this.szOffset);
        
        // Robot's rotation
        this.angle = 0;
        this.shootAngle = 0;
        this.range = [2, 10];
        
        // Robot's velocity and movement
        this.v = { x: 0, y: 0 };
        this.falling = false;
        this.grav = 0.5;
        this.jumpReload = 60;
        
        // Robot's health
        this.health = 100;
        this.displayHealth = 100;
    };
    _Robot.prototype.draw = function() {
        pushMatrix();
        imageMode(CENTER);
        translate(this.x+this.w/2, this.y+this.h/2);
        rotate(this.angle);
        image(imgs.robot, 0, 0, this.w, this.h);
        rectMode(CENTER);
        rotate(-this.angle);
        fill(255, 0, 0);
        rect(0, -this.h / 1.5, 100, 15);
        fill(0, 255, 0);
        rect(0, -this.h / 1.5, this.displayHealth, 15);
        popMatrix();
        rectMode(CORNER);
        imageMode(CORNER);
    };
    _Robot.prototype.move = function() {
        this.shootAngle = atan2(Day.y - this.y, Day.x - this.x);
        
        const distance = dist(this.x, this.y, Day.x, Day.y);
        if (distance >= BLOCKSIZE * this.range[0] && dist(this.x, this.y, Day.x, Day.y) <= BLOCKSIZE * this.range[1]){
            if (this.x < Day.x){
                this.v.x = 3;
                if (!this.falling && this.jumpReload <= 0){
                    this.v.y = -10;
                    this.falling = true;
                    this.jumpReload = 60;
                    
                }
            } else if (this.x > Day.x){
                this.v.x = -3;
                if (!this.falling && this.jumpReload <= 0){
                    this.v.y = -10;
                    this.falling = true;
                    this.jumpReload = 60;
                }
            } else {
                this.v.x = 0;
            }
            
        } else {
            this.v.x = 0;
        }
        
        if (distance <= BLOCKSIZE * this.range[1]){
            
            if (game.timer % 60 === 0){
                bullets.push(new Bullet({
                    x: this.x+20,
                    y: this.y+20,
                    angle: this.shootAngle,
                    type: "laser",
                    origin: "enemy",
                }));
            }
        }
        
        if (this.jumpReload < 20 && this.jumpReload > 10){
            cam.shake(3 + this.szOffset);
        }
        if (this.jumpReload === 20){
            for (let i = 0; i < 10; i ++){
                particles.push(new Particle({x:this.x+this.h/2, y:this.y+this.h, maxSpeed: 3, clr: color(255), dir: ["left",'right'][round(Math.random())], sz: 10}));
            }
        }
        
        this.jumpReload --;
        
        this.x += this.v.x;
        this.angle += this.v.x;
        
        this.collide(this.v.x, 0);
        
        this.y += this.v.y;
        this.v.y += this.grav;
        this.collide(0, this.v.y);
        
        if (this.health <= 0){
            for (let i = 0; i < 50; i ++){
                particles.push(new Particle({x:this.x+this.h/2, y:this.y+this.h, maxSpeed: 3, clr: color(255), dir: ["left",'right'][round(Math.random())], sz: 5}));
            }
            this.dead = true;
        }
        this.displayHealth = lerp(this.displayHealth, this.health, 0.1);
    };
    _Robot.prototype.collide = function(vx, vy){
        const objs = [blocks, Object.values(boundingBoxes), bullets];
        for (let o in objs){
            const obj = objs[o];
            for (let i in obj){
                if (obj[i] instanceof Block ||
                    obj[i] instanceof BoundingBox){
                    if (rectRect(this, obj[i])&&(obj[i].lvl!==undefined?game.lvl===obj[i].lvl:true)){
                        if (!obj[i].falling){
                            if (vx > 0){
                                this.v.x = 0;
                                this.x = obj[i].x - this.w;
                            }
                            if (vx < 0){
                                this.v.x = 0;
                                this.x = obj[i].x + obj[i].w;
                            }
                            if (vy > 0){
                                this.v.y = 0;
                                this.falling = false;
                                this.y = obj[i].y - this.h;
                                if(obj[i] instanceof Block){if (obj[i].type.includes("spike_up")){
                                    this.v.y = -5;
                                    this.health -= 2;
                                }}
                            }
                            if (vy < 0){
                                this.v.y = 0;
                                this.falling = true;
                                this.y = obj[i].y + obj[i].h;
                            }
                        } else {
                            this.health -= 0.2;
                        }
                    }
                }
                if (obj[i] instanceof Bullet){
                    if (rectRect(this, obj[i]) &&
                        obj[i].origin === "player"){
                        this.health -= 20;
                        obj[i].dead = true;
                    }
                }
            }
        }
    };
    _Robot.prototype.run = function(){
        this.draw();
        if (!game.inactive){
            this.move();
        }
    };
    return _Robot;
})();

